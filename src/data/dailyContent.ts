/**
 * Returns local calendar YYYY-MM-DD key so content stays fixed for the entire local calendar day
 * and deterministically rotates at midnight (00:00).
 */
export function getLocalCalendarDateKey(date: Date = new Date()): string {
  const y = date.getFullYear();
  const m = String(date.getMonth() + 1).padStart(2, '0');
  const d = String(date.getDate()).padStart(2, '0');
  return `${y}-${m}-${d}`;
}

/**
 * Deterministic day index based on local calendar year/month/day.
 */
export function getDailyDayNumber(date: Date = new Date()): number {
  const utcDay = Math.floor(Date.UTC(date.getFullYear(), date.getMonth(), date.getDate()) / 86400000);
  return Math.abs(utcDay);
}

export function getDailyIslamicContent(date: Date = new Date()): DailyIslamicContent {
  const dateKey = getLocalCalendarDateKey(date);
  const daySeed = getDailyDayNumber(date);

  const ayah = DAILY_AYAHS_POOL[daySeed % DAILY_AYAHS_POOL.length];
  const hadith = DAILY_HADITHS_POOL[(daySeed + 7) % DAILY_HADITHS_POOL.length];
  const dua = DAILY_DUAS_POOL[(daySeed + 13) % DAILY_DUAS_POOL.length];

  return {
    dateKey,
    daySeed,
    ayah,
    hadith,
    dua,
  };
}
