const FAVORITES_STORAGE_KEY = 'moazen_encyclopedia_favorites_v1';

export function getSavedFavorites(): string[] {
  try {
    const raw = localStorage.getItem(FAVORITES_STORAGE_KEY);
    return raw ? JSON.parse(raw) : [];
  } catch {
    return [];
  }
}

export function toggleSavedFavorite(itemId: string): string[] {
  const current = getSavedFavorites();
  const next = current.includes(itemId)
    ? current.filter((id) => id !== itemId)
    : [...current, itemId];
  try {
    localStorage.setItem(FAVORITES_STORAGE_KEY, JSON.stringify(next));
    window.dispatchEvent(new CustomEvent('favoritesUpdated', { detail: next }));
  } catch {
    // ignore
  }
  return next;
}

