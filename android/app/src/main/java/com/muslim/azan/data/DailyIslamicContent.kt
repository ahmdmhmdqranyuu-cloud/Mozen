    fun getTodaySnapshot(calendar: Calendar = Calendar.getInstance()): DailyIslamicSnapshot {
        val y = calendar.get(Calendar.YEAR)
        val m = calendar.get(Calendar.MONTH) + 1
        val d = calendar.get(Calendar.DAY_OF_MONTH)
        val dateKey = String.format(java.util.Locale.US, "%04d-%02d-%02d", y, m, d)

        val utcCal = Calendar.getInstance(java.util.TimeZone.getTimeZone("UTC")).apply {
            clear()
            set(y, calendar.get(Calendar.MONTH), d, 0, 0, 0)
        }
        val daySeed = abs(TimeUnit.MILLISECONDS.toDays(utcCal.timeInMillis)).toInt()

        return DailyIslamicSnapshot(
            dateKey = dateKey,
            ayah = ayahs[daySeed % ayahs.size],
            hadith = hadiths[(daySeed + 5) % hadiths.size],
            dua = duas[(daySeed + 9) % duas.size]
        )
    }
